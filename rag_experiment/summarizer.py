def summarize_article(title, content):
    """
    기사 제목과 내용을 받아
    뉴스레터에 사용할 수 있는 짧은 요약문을 만든다.
    """

    # --------------------------------------
    # 현재는 테스트용 요약
    # --------------------------------------

    # 너무 긴 기사 내용은 일정 길이까지만 사용
    summary = content[:500]

    return {
        "title": title,
        "summary": summary
    }